export type PreviewKind = "image" | "pdf";

/** ไฟล์ที่พร้อมเอาไปแสดงในกล่องดูไฟล์ — url เป็น signed URL ที่ขอมาแล้ว */
export type PreviewItem = {
  id: string;
  name: string;
  kind: PreviewKind;
  url: string;
};

/**
 * อายุลิงก์สำหรับดู — ยาวกว่าลิงก์ดาวน์โหลดมาก
 *
 * ลิงก์ดาวน์โหลดใช้ครั้งเดียวทันทีที่กด 60 วินาทีจึงเหลือเฟือ
 * แต่ลิงก์สำหรับดูต้องอยู่ได้ตลอดเวลาที่กล่องเปิดค้าง รวมถึงตอนเลื่อนดูไฟล์ถัดไป
 * และตอนอ่าน PDF ยาว ๆ ซึ่งกินเวลาเป็นนาที
 */
export const PREVIEW_URL_SECONDS = 600;

const IMAGE_EXT = ["png", "jpg", "jpeg", "gif", "webp", "avif", "svg", "bmp"];

/**
 * ไฟล์นี้เปิดดูได้ไหม และเป็นชนิดไหน
 *
 * ดู mime_type ก่อนเพราะเป็นค่าที่เบราว์เซอร์บอกมาตอนอัป แม่นกว่านามสกุล
 * แต่ต้องตกมาดูนามสกุลด้วย เพราะแถวไฟล์เก่าที่อัปก่อน 0009 ไม่มี mime_type
 * และบางระบบส่ง 'application/octet-stream' มาให้ทุกไฟล์ไม่ว่าเป็นอะไร
 */
export function previewKind(mime: string | null, name: string): PreviewKind | null {
  const m = (mime ?? "").toLowerCase();
  if (m.startsWith("image/")) return "image";
  if (m === "application/pdf") return "pdf";

  const ext = name.toLowerCase().split(".").pop() ?? "";
  if (IMAGE_EXT.includes(ext)) return "image";
  if (ext === "pdf") return "pdf";

  return null;
}
