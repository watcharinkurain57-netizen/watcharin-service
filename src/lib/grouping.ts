/**
 * จัดของลงหมวด — ใช้ร่วมกันระหว่างงาน (0014) และไดอะแกรม (0021)
 *
 * ---------------------------------------------------------------------------
 * ทำไมต้องเป็นตัวกลาง ไม่ใช่ก๊อปไปเขียนซ้ำที่ละที่
 *
 * ตรรกะนี้มีกับดักหนึ่งข้อที่มองไม่เห็นด้วยตา (อ่าน `loose` ข้างล่าง)
 * ถ้ามีสำเนาสองชุด วันที่แก้กับดักนั้นจะแก้แค่ชุดเดียว แล้วอีกชุด
 * จะทำของหายเงียบ ๆ ต่อไปโดยไม่มีใครรู้ เพราะอาการมันไม่ error
 * ---------------------------------------------------------------------------
 */

/** อะไรก็ได้ที่เป็นหมวด ขอแค่มี id ชื่อ และลำดับ */
export type Bucketable = { id: string; name: string; sort: number };

/**
 * จัดของลงหมวด พร้อมถังท้ายสำหรับของที่ยังไม่ได้จัด
 *
 * คืนหมวดที่ไม่มีของมาด้วย (`items` ว่าง) เพื่อให้ผู้ใช้เห็นว่าหมวดที่ตั้งไว้
 * ยังว่างอยู่ ไม่ใช่หายไปเฉย ๆ — ฝั่งที่เรียกเป็นคนตัดสินเองว่าจะซ่อนไหม
 */
export function bucketBy<TItem, TGroup extends Bucketable>(
  items: TItem[],
  groups: TGroup[],
  groupIdOf: (item: TItem) => string | null
): { group: TGroup | null; items: TItem[] }[] {
  const known = new Set(groups.map((g) => g.id));

  const buckets = [...groups]
    .sort((a, b) => a.sort - b.sort || a.name.localeCompare(b.name, "th"))
    .map((group) => ({
      group: group as TGroup | null,
      items: items.filter((t) => groupIdOf(t) === group.id),
    }));

  /**
   * ถังท้าย = ของที่ไม่มีหมวด **และ** ของที่ชี้หมวดซึ่งหาไม่เจอ
   *
   * ⚠️ เงื่อนไขที่สองสำคัญกว่าที่คิด ถ้าเช็คแค่ว่าไม่มี group_id
   * ของที่ชี้หมวดแปลกปลอมจะไม่เข้าถังไหนเลย = **หายไปจากทุกมุมมองแบบเงียบ ๆ**
   * เกิดได้จริงตอนโหลดรายการหมวดไม่สำเร็จแต่โหลดตัวของสำเร็จ
   * (เป็นอาการเดียวกับที่ 0005 เตือนไว้เรื่อง column_id — งานหลุดออกจากบอร์ด)
   */
  const loose = items.filter((t) => {
    const id = groupIdOf(t);
    return !id || !known.has(id);
  });

  // ไว้ท้ายสุดเสมอ ไม่ใช่บนสุด — ถ้าอยู่บนสุดจะบังหมวดที่ตั้งใจจัดไว้
  // ซึ่งเป็นของที่ผู้ใช้อยากเห็นก่อน
  if (loose.length > 0) buckets.push({ group: null, items: loose });

  return buckets;
}
